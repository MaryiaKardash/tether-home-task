export function photoUrl(photo: Photo, layoutWidth: number): string {
  const id = UNSPLASH_IDS[(photo.id - 1) % UNSPLASH_IDS.length];
  const w = PixelRatio.getPixelSizeForLayoutSize(layoutWidth);
  const h = Math.round((w * photo.height) / photo.width);
  return `https://images.unsplash.com/photo-${id}?w=${w}&h=${h}&fit=crop&auto=format&q=75`;
}
